"""Synthetic-only, offline QA for the photo review gate, no external media."""

import importlib.util
import json
from pathlib import Path
import tempfile
import unittest

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SPEC = importlib.util.spec_from_file_location("offline_photo_review", ROOT / "tools/offline_photo_review.py")
review = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(review)


def sample(id_, filename, **overrides):
    return {"vehicle_id": id_, "file": filename,
            "creator_claim": "Synthetic Test Author", "licence_claim": "Test source, not redistributable",
            "source_note": "Generated by unit test; no real rental vehicle", **overrides}


class OfflinePhotoReviewTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.base = Path(self.temp.name)
        self.originals = self.base / "originals"
        self.originals.mkdir()
        self.manifest = self.base / "manifest.json"
        self.out = self.base / "results"

    def put(self, entries):
        self.manifest.write_text(json.dumps({"candidates": entries}), encoding="utf-8")

    def image(self, filename="C003.png", **options):
        photo = Image.new("RGB", (800, 600), (72, 151, 170))
        photo.save(self.originals / filename, **options)
        return photo

    def test_single_i20_review_retains_original_and_unapproved_rights(self):
        self.image()
        self.put([sample("C003", "C003.png")])
        before = (self.originals / "C003.png").read_bytes()
        result = review.run(self.originals, self.manifest, self.out)
        self.assertEqual(result["candidate_count"], 1)
        self.assertFalse(result["full_five_model_set"])
        self.assertFalse(result["candidates"][0]["rights_verified"])
        self.assertFalse(result["candidates"][0]["owner_visual_approved"])
        self.assertEqual(before, (self.originals / "C003.png").read_bytes())
        self.assertTrue((self.out / "CONTACT_SHEET_UNAPPROVED.png").is_file())
        self.assertEqual((self.out / "REVIEW_MANIFEST.json").is_file(), True)
        with Image.open(self.out / "C003-review-only-normalized.jpg") as img:
            self.assertEqual(img.format, "JPEG")
            self.assertFalse(img.getexif())

    def test_five_model_partial_order_and_real_derived_hashes(self):
        entries = []
        for id_ in review.MODEL_IDS:
            filename = id_ + ".png"
            self.image(filename)
            entries.append(sample(id_, filename))
        self.put(entries)
        result = review.run(self.originals, self.manifest, self.out)
        self.assertTrue(result["full_five_model_set"])
        self.assertEqual(len(result["candidates"]), 5)
        for row in result["candidates"]:
            blob = (self.out / row["review_derivative"]).read_bytes()
            self.assertEqual(review.sha256(blob), row["review_derivative_sha256"])
            self.assertFalse(row["installed_in_application"])

    def test_path_traversal_refused_without_writes(self):
        self.put([sample("C003", "../secret.png")])
        with self.assertRaises(review.ReviewError):
            review.run(self.originals, self.manifest, self.out)
        self.assertFalse(self.out.exists())

    def test_symlink_source_refused(self):
        outside = self.base / "outside.jpg"
        Image.new("RGB", (800, 600), (1, 2, 3)).save(outside)
        try:
            (self.originals / "C003.jpg").symlink_to(outside)
        except (OSError, NotImplementedError) as exc:
            self.skipTest(f"OS does not permit creating a test symlink: {exc}")
        self.put([sample("C003", "C003.jpg")])
        with self.assertRaises(review.ReviewError):
            review.run(self.originals, self.manifest, self.out)
        self.assertFalse(self.out.exists())

    def test_oversize_or_mismatched_image_refused(self):
        (self.originals / "C003.jpg").write_bytes(b"not-a-photo")
        self.put([sample("C003", "C003.jpg")])
        with self.assertRaises(review.ReviewError):
            review.run(self.originals, self.manifest, self.out)
        self.assertFalse(self.out.exists())

    def test_invalid_or_duplicate_vehicle_identity_refused(self):
        self.put([sample("C003", "a.png"), sample("C003", "b.png")])
        with self.assertRaises(review.ReviewError):
            review.run(self.originals, self.manifest, self.out)
        self.put([sample("M999", "a.png")])
        with self.assertRaises(review.ReviewError):
            review.run(self.originals, self.manifest, self.out)

    def test_output_preexisting_data_preserved(self):
        self.image()
        self.put([sample("C003", "C003.png")])
        self.out.mkdir()
        evidence = self.out / "important.txt"
        evidence.write_text("Keep this", encoding="utf-8")
        with self.assertRaises(review.ReviewError):
            review.run(self.originals, self.manifest, self.out)
        self.assertEqual(evidence.read_text(), "Keep this")

    def test_app_assets_directory_refused(self):
        with self.assertRaises(review.ReviewError):
            review.safe_output(self.originals, review.PROTECTED_ASSETS / "review")

    def test_real_source_exif_removed_from_review_jpeg(self):
        photo = Image.new("RGB", (800, 600), (10, 20, 30))
        exif = Image.Exif()
        exif[0x010E] = "Synthetic source metadata must not survive"
        photo.save(self.originals / "C003.jpg", exif=exif)
        with Image.open(self.originals / "C003.jpg") as original:
            self.assertIn(0x010E, original.getexif())
        source_bytes = (self.originals / "C003.jpg").read_bytes()
        self.put([sample("C003", "C003.jpg")])
        result = review.run(self.originals, self.manifest, self.out)
        with Image.open(self.out / "C003-review-only-normalized.jpg") as output:
            self.assertNotIn(0x010E, output.getexif())
            self.assertFalse(output.getexif())
        self.assertEqual(result["candidates"][0]["original_sha256"], review.sha256(source_bytes))
        self.assertEqual(source_bytes, (self.originals / "C003.jpg").read_bytes())

    def test_file_larger_than_input_limit_refused(self):
        with (self.originals / "C003.jpg").open("wb") as out:
            out.seek(review.MAX_INPUT_BYTES)
            out.write(b"X")
        self.put([sample("C003", "C003.jpg")])
        with self.assertRaises(review.ReviewError):
            review.run(self.originals, self.manifest, self.out)
        self.assertFalse(self.out.exists())

    def test_transparent_png_exif_stripping_and_crop(self):
        photo = Image.new("RGBA", (700, 500), (0, 0, 0, 0))
        photo.putpixel((30, 40), (150, 60, 50, 255))
        photo.save(self.originals / "C003.png")
        self.put([sample("C003", "C003.png")])
        review.run(self.originals, self.manifest, self.out)
        with Image.open(self.out / "C003-review-only-normalized.jpg") as output:
            self.assertEqual(output.mode, "RGB")
            self.assertFalse(output.getexif())


if __name__ == "__main__":
    unittest.main()